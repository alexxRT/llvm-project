#ifndef LLVM_LIB_TARGET_X52_X52SUBTARGET_H
#define LLVM_LIB_TARGET_X52_X52SUBTARGET_H

#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "X52FrameLowering.h"
#include "X52RegisterInfo.h"
#include "X52ISelLowering.h"
#include "X52InstrInfo.h"
#define GET_SUBTARGETINFO_HEADER
#include "X52GenSubtargetInfo.inc"


namespace llvm {

class X52Subtarget : public X52GenSubtargetInfo {
    public:
        X52Subtarget(const Triple &TT, const std::string &CPU, const std::string &FS, const TargetMachine &TM);

        /// ParseSubtargetFeatures - Parses features string setting specified
        /// subtarget options.  Definition of function is auto generated by tblgen.
        void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

        const X52TargetLowering* getTargetLowering() const override { return &TLInfo; };

        const TargetRegisterInfo* getRegisterInfo() const override { return &RegisterInfo; };

        const X52FrameLowering* getFrameLowering() const override { return &FrameLowering; };

        const X52InstrInfo* getInstrInfo() const override { return &InstrInfo; };

        const SelectionDAGTargetInfo* getSelectionDAGInfo() const override { return &TSInfo; };

    private:
        X52TargetLowering TLInfo;
        X52FrameLowering FrameLowering;
        X52RegisterInfo RegisterInfo;
        X52InstrInfo InstrInfo;
        SelectionDAGTargetInfo TSInfo;
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_X52_X52SUBTARGET_H